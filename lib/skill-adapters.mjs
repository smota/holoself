import {
  existsSync,
  lstatSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  realpathSync,
  writeFileSync,
} from 'node:fs'
import { dirname, isAbsolute, join, relative, resolve, sep } from 'node:path'
import { createHash } from 'node:crypto'
import { loadSkillCatalog } from './skill-catalog.mjs'

export const HARNESS_TARGETS = {
  'claude-code': '.claude/skills',
  pi: '.pi/skills',
  agy: '.agents/skills',
  codex: '.agents/skills',
}

export function syncSkillAdapters({
  packageRoot,
  targetDir,
  harness = 'all',
  write = false,
  captureContent = false,
} = {}) {
  const harnesses = harness === 'all' ? Object.keys(HARNESS_TARGETS) : String(harness).split(',')
  const catalog = loadSkillCatalog(packageRoot)
  const planned = []
  const captured = []
  for (const skill of catalog.skills) {
    const adapterName = skill.qualifiedName
    const sourceRoot = join(packageRoot, skill.source)
    const files = listFiles(sourceRoot)
    for (const item of harnesses) {
      const root = HARNESS_TARGETS[item]
      if (!root) throw new Error(`Unknown harness: ${item}`)
      for (const source of files) {
        const relativePath = relative(sourceRoot, source)
        const target = join(targetDir, root, adapterName, relativePath)
        const skillRootTarget = join(targetDir, root, adapterName)
        const content = readFileSync(source, 'utf8')
        const generated =
          relativePath === 'SKILL.md'
            ? renderAdapter({ content, source: `${skill.source}/SKILL.md`, adapterName })
            : content
        const linkInfo = inspectLinkedSkillTarget({
          targetDir,
          target,
          source,
          skillRootTarget,
          canonicalSkillRoot: sourceRoot,
        })
        const status = linkInfo.linked
          ? linkInfo.status
          : existsSync(target) && readFileSync(target, 'utf8') === generated
            ? 'unchanged'
            : 'planned'
        planned.push({
          skill: skill.qualifiedName,
          adapterName,
          qualifiedName: skill.qualifiedName,
          harness: item,
          source: `${skill.source}/${relativePath.replaceAll('\\', '/')}`,
          target,
          status,
          ...(linkInfo.linked ? { linked: true } : {}),
          hash:
            linkInfo.linked && linkInfo.status === 'linked-canonical'
              ? hash(content)
              : hash(generated),
        })
        if (captureContent && !linkInfo.linked && existsSync(target))
          captured.push({ target, content: generated })
        if (!linkInfo.linked && write && status !== 'unchanged') {
          mkdirSync(dirname(target), { recursive: true })
          writeFileSync(target, generated)
        }

        // Generate slash command for skill on main SKILL.md
        if (relativePath === 'SKILL.md' && (item === 'claude-code' || item === 'pi')) {
          const cmdDir = item === 'claude-code' ? '.claude/commands' : '.pi/commands'
          const cmdTarget = join(targetDir, cmdDir, `${adapterName}.md`)
          const cmdContent = `<!-- GENERATED BY AgentFlow SDLC. Do not edit. -->\n# Skill: ${skill.qualifiedName}\n\nExecute the skill \`${adapterName}\` following instructions in \`${root}/${adapterName}/SKILL.md\`.\n`
          const cmdLinked = Boolean(hasSymlinkAlongPath(targetDir, cmdTarget))
          const cmdStatus = cmdLinked
            ? 'linked-noncanonical'
            : existsSync(cmdTarget) && readFileSync(cmdTarget, 'utf8') === cmdContent
              ? 'unchanged'
              : 'planned'
          planned.push({
            skill: skill.qualifiedName,
            adapterName,
            qualifiedName: skill.qualifiedName,
            harness: `${item}:command`,
            source: `${skill.source}/SKILL.md`,
            target: cmdTarget,
            status: cmdStatus,
            ...(cmdLinked ? { linked: true } : {}),
            hash: hash(cmdContent),
          })
          if (captureContent && !cmdLinked)
            captured.push({ target: cmdTarget, content: cmdContent })
          if (!cmdLinked && write && cmdStatus !== 'unchanged') {
            mkdirSync(dirname(cmdTarget), { recursive: true })
            writeFileSync(cmdTarget, cmdContent)
          }

          if (skill.role === 'maintainer') {
            const actionDir =
              item === 'claude-code' ? '.claude/commands/agentflow' : '.pi/commands/agentflow'
            const actions = [
              {
                name: 'setup',
                title: 'Setup',
                desc: 'Adopt AgentFlow SDLC in this project conversationally.',
              },
              {
                name: 'doctor',
                title: 'Doctor',
                desc: 'Inspect AgentFlow SDLC project health, drift, and adapter sync.',
              },
              {
                name: 'repair',
                title: 'Repair',
                desc: 'Plan and apply transactional configuration repair for detected drift.',
              },
              {
                name: 'undo',
                title: 'Undo',
                desc: 'Undo the most recent AgentFlow transaction or roll back using a receipt.',
              },
            ]
            for (const action of actions) {
              const actionTarget = join(targetDir, actionDir, `${action.name}.md`)
              const actionContent = `<!-- GENERATED BY AgentFlow SDLC. Do not edit. -->\n# AgentFlow ${action.title}\n\n${action.desc}\nExecute the skill \`${adapterName}\` with journey \`${action.name}\`.\n`
              const actionLinked = Boolean(hasSymlinkAlongPath(targetDir, actionTarget))
              const actionStatus = actionLinked
                ? 'linked-noncanonical'
                : existsSync(actionTarget) && readFileSync(actionTarget, 'utf8') === actionContent
                  ? 'unchanged'
                  : 'planned'
              planned.push({
                skill: skill.qualifiedName,
                adapterName,
                qualifiedName: skill.qualifiedName,
                harness: `${item}:command`,
                source: `${skill.source}/SKILL.md`,
                target: actionTarget,
                status: actionStatus,
                ...(actionLinked ? { linked: true } : {}),
                hash: hash(actionContent),
              })
              if (captureContent && !actionLinked)
                captured.push({ target: actionTarget, content: actionContent })
              if (!actionLinked && write && actionStatus !== 'unchanged') {
                mkdirSync(dirname(actionTarget), { recursive: true })
                writeFileSync(actionTarget, actionContent)
              }
            }
          }
        }
      }
    }
  }
  const manifestPath = join(targetDir, '.agentflow-adapters.lock.json')
  if (write)
    writeFileSync(
      manifestPath,
      `${JSON.stringify({ version: 2, namespace: catalog.namespace, entries: planned }, null, 2)}\n`,
    )
  const result = { ok: true, mode: write ? 'apply' : 'dry-run', entries: planned, manifestPath }
  if (captureContent) result.captured = captured
  return result
}

export { hasSymlinkAlongPath }

export function adapterStatus({ packageRoot, targetDir, harness = 'all' } = {}) {
  const result = syncSkillAdapters({ packageRoot, targetDir, harness, write: false })
  return {
    ...result,
    stale: result.entries.filter(
      (entry) => entry.status !== 'unchanged' && entry.status !== 'linked-canonical',
    ),
    linkedCanonical: result.entries.filter((entry) => entry.status === 'linked-canonical'),
    linkedNonCanonical: result.entries.filter(
      (entry) => entry.status === 'linked-noncanonical' || entry.status === 'linked-broken',
    ),
  }
}

function hasSymlinkAlongPath(rootDir, targetPath) {
  const root = resolve(rootDir)
  const target = resolve(targetPath)
  if (!isAbsolute(target) || (target !== root && !target.startsWith(root + sep))) return null
  let current = root
  for (const segment of relative(root, target).split(sep).filter(Boolean)) {
    current = join(current, segment)
    try {
      if (lstatSync(current).isSymbolicLink()) return current
    } catch (error) {
      if (error.code === 'ENOENT') return null
      throw error
    }
  }
  return null
}

function inspectLinkedSkillTarget({
  targetDir,
  target,
  source,
  skillRootTarget,
  canonicalSkillRoot,
}) {
  const symlinkPath = hasSymlinkAlongPath(targetDir, target)
  if (!symlinkPath) return { linked: false }
  const skillRoot = resolve(skillRootTarget)
  if (symlinkPath !== skillRoot && !symlinkPath.startsWith(skillRoot + sep)) {
    return {
      linked: true,
      status: 'linked-noncanonical',
      symlinkPath,
      reason: 'harness-root-symlink',
    }
  }
  try {
    const realTarget = realpathSync(target)
    const realSource = realpathSync(source)
    realpathSync(canonicalSkillRoot)
    const targetBytes = readFileSync(realTarget, 'utf8')
    const sourceBytes = readFileSync(realSource, 'utf8')
    if (realTarget === realSource || targetBytes === sourceBytes) {
      return { linked: true, status: 'linked-canonical', symlinkPath, resolvedTarget: realTarget }
    }
    return {
      linked: true,
      status: 'linked-noncanonical',
      symlinkPath,
      resolvedTarget: realTarget,
      reason: 'content-mismatch',
    }
  } catch {
    return { linked: true, status: 'linked-broken', symlinkPath, reason: 'broken-link' }
  }
}

function renderAdapter({ content, source, adapterName }) {
  const frontmatter = content.match(/^---\r?\n[\s\S]*?\r?\n---/)
  if (!frontmatter) throw new Error(`Skill source lacks frontmatter: ${source}`)
  const adapterFrontmatter = frontmatter[0].replace(/^name:\s*[^\r\n]+$/m, `name: ${adapterName}`)
  const body = content.slice(frontmatter[0].length).replace(/^\r?\n/, '')
  return `${adapterFrontmatter}\n<!-- GENERATED BY AgentFlow SDLC. Do not edit. Source: ${source}. -->\n${body.trimEnd()}\n\n## Generated adapter note\n\nThis adapter preserves the canonical \`${adapterName}\` skill name. Regenerate with \`agentflow-sdlc skills sync --harness all\`.\n`
}

function listFiles(directory) {
  const files = []
  for (const entry of readdirSync(directory, { withFileTypes: true })) {
    const path = join(directory, entry.name)
    if (entry.isDirectory()) files.push(...listFiles(path))
    else files.push(path)
  }
  return files.sort()
}

function hash(value) {
  return createHash('sha256').update(value).digest('hex')
}
