import { createHash } from 'node:crypto'
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { loadMethodCatalog, loadRoleCatalog } from './role-catalog.mjs'

export const HARNESS_ROLE_TARGETS = {
  'claude-code': '.agentflow/roles/claude-code',
  codex: '.agentflow/roles/codex',
  agy: '.agentflow/roles/agy',
  pi: '.agentflow/roles/pi',
}

export function syncRoleAdapters({ packageRoot, targetDir, harness = 'all', write = false } = {}) {
  const catalog = loadRoleCatalog(packageRoot)
  const methodCatalog = loadMethodCatalog(packageRoot)
  const harnesses =
    harness === 'all' ? Object.keys(HARNESS_ROLE_TARGETS) : String(harness).split(',')
  for (const harnessName of harnesses) {
    if (!HARNESS_ROLE_TARGETS[harnessName]) throw new Error(`Unknown harness: ${harnessName}`)
  }
  const entries = []
  const seenTargets = new Set()
  for (const harnessName of harnesses) {
    const adapterRoot = HARNESS_ROLE_TARGETS[harnessName]
    for (const role of catalog.roles) {
      const target = join(targetDir, adapterRoot, `${catalog.namespace}-${role.slug}.md`)
      const content = renderRoleAdapter({
        source: readFileSync(join(packageRoot, role.source, 'ROLE.md'), 'utf8'),
        role,
        harness: harnessName,
      })
      const status =
        existsSync(target) && readFileSync(target, 'utf8') === content ? 'unchanged' : 'planned'
      entries.push({
        harness: harnessName,
        role: role.qualifiedName,
        target,
        status,
        hash: digest(content),
      })
      if (write && status !== 'unchanged') {
        mkdirSync(dirname(target), { recursive: true })
        writeFileSync(target, content)
      }
      seenTargets.add(target)

      // Project slash command for harness when applicable
      if (harnessName === 'claude-code' || harnessName === 'pi') {
        const cmdDir = harnessName === 'claude-code' ? '.claude/commands' : '.pi/commands'
        const cmdTarget = join(targetDir, cmdDir, `role-${role.slug}.md`)
        const cmdContent = renderRoleCommand({ role, harness: harnessName })
        const cmdStatus =
          existsSync(cmdTarget) && readFileSync(cmdTarget, 'utf8') === cmdContent
            ? 'unchanged'
            : 'planned'
        entries.push({
          harness: `${harnessName}:command`,
          role: role.qualifiedName,
          target: cmdTarget,
          status: cmdStatus,
          hash: digest(cmdContent),
        })
        if (write && cmdStatus !== 'unchanged') {
          mkdirSync(dirname(cmdTarget), { recursive: true })
          writeFileSync(cmdTarget, cmdContent)
        }
        seenTargets.add(cmdTarget)
      }
    }
  }
  const catalogTargets = [
    ['role-catalog.json', catalog],
    ['method-catalog.json', methodCatalog],
  ]
  for (const [name, value] of catalogTargets) {
    const target = join(targetDir, '.agentflow', name)
    const content = `${JSON.stringify(value, null, 2)}\n`
    const status =
      existsSync(target) && readFileSync(target, 'utf8') === content ? 'unchanged' : 'planned'
    entries.push({ harness: 'shared', role: null, target, status, hash: digest(content) })
    if (write && status !== 'unchanged') {
      mkdirSync(dirname(target), { recursive: true })
      writeFileSync(target, content)
    }
    seenTargets.add(target)
  }
  const lockPath = join(targetDir, '.agentflow-role-adapters.lock.json')
  if (write) {
    const lock = { version: 1, namespace: catalog.namespace, entries }
    writeFileSync(lockPath, `${JSON.stringify(lock, null, 2)}\n`)
  }
  return { ok: true, mode: write ? 'apply' : 'dry-run', entries, lockPath }
}

export function roleAdapterStatus(options = {}) {
  const result = syncRoleAdapters({ ...options, write: false })
  return { ...result, stale: result.entries.filter((entry) => entry.status !== 'unchanged') }
}

function renderRoleAdapter({ source, role, harness }) {
  return `<!-- GENERATED BY AgentFlow SDLC. Do not edit. Source: ${role.source}/ROLE.md. -->\n<!-- Harness projection: ${harness}; canonical identity: ${role.qualifiedName}. -->\n\n${source.trimEnd()}\n`
}

function renderRoleCommand({ role, harness }) {
  return `<!-- GENERATED BY AgentFlow SDLC. Do not edit. -->
# Role: ${role.label} (\`${role.qualifiedName}\`)

${role.purpose}

## Authority & Boundaries
- Default boundary: \`${role.authority?.defaultBoundary ?? 'propose'}\`
- Maximum boundary: \`${role.authority?.maximumBoundary ?? 'propose'}\`

## Activation Prompt
You are now operating in the **${role.label}** role (Phase ${role.phase ?? 'N/A'}).
Follow the lifecycle rules, handoffs, and verification contracts defined for \`${role.qualifiedName}\`.
Produce a formal role-pass upon task completion.
`
}

function digest(value) {
  return createHash('sha256').update(value).digest('hex')
}
